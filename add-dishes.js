(async () => {
  const existingRecipes = await query("SELECT title FROM recipes");
  const existingTitles = new Set(existingRecipes.map((recipe) => recipe.title));
  let total = existingRecipes.length;
  const extraDishes = additionalRecipes.map((recipe) => [
    2,
    recipe.title,
    recipe.description,
    recipe.image,
    recipe.category,
    recipe.country,
    recipe.prep_minutes,
    recipe.cook_minutes,
    recipe.servings,
    recipe.difficulty,
    recipe.calories,
    recipe.protein,
    recipe.carbs,
    recipe.fat,
    recipe.diet,
    recipe.ingredients.map(({ name, quantity, unit }) => [
      name,
      quantity,
      unit,
    ]),
    recipe.steps,
    recipe.views,
  ]);
  for (const d of [...dishes, ...extraDishes]) {
    const [
      uid,
      title,
      desc,
      img,
      cat,
      country,
      prep,
      cook,
      serv,
      diff,
      cal,
      p,
      c,
      f,
      diet,
      ings,
      steps,
      views,
    ] = d;
    if (total >= 50) break;
    if (existingTitles.has(title)) continue;

    const cats = await query("SELECT id FROM categories WHERE name=?", cat);
    const catId = cats.length
      ? cats[0].id
      : (
          await exec("INSERT INTO categories (name,icon) VALUES (?,?)", [
            cat,
            "🍽️",
          ])
        ).insertId;
    const id = (
      await exec(
        `INSERT INTO recipes (user_id,title,description,image,video_url,category_id,country,prep_minutes,cook_minutes,servings,difficulty,calories,protein,carbs,fat,diet,is_public,views)
      VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
        [
          uid,
          title,
          desc,
          img,
          "",
          catId,
          country,
          prep,
          cook,
          serv,
          diff,
          cal,
          p,
          c,
          f,
          diet,
          1,
          views,
        ],
      )
    ).insertId;
    for (const [n, q, u] of ings)
      await exec(
        "INSERT INTO recipe_ingredients (recipe_id,name,quantity,unit) VALUES (?,?,?,?)",
        [id, n, q, u],
      );
    let so = 0;
    for (const s of steps)
      await exec(
        "INSERT INTO recipe_steps (recipe_id,step_order,text) VALUES (?,?,?)",
        [id, ++so, s],
      );
    console.log(`+ ${title} (id=${id})`);
    existingTitles.add(title);
    total += 1;
  }
  const finalCount = (await query("SELECT COUNT(*) c FROM recipes"))[0].c;
  console.log(`TONG CON: ${finalCount} mon an`);
  if (finalCount < 50)
    throw new Error(`Only ${finalCount} recipes found; expected 50.`);
  process.exit(0);
})().catch((e) => {
  console.error("ERR:", e.message);
  process.exit(1);
});
